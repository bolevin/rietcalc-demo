"""Build the full unit-cell content from the asymmetric unit.

Every operator is applied to every independent atom and the results are folded
back into the cell.  An atom on a special position is mapped onto itself by some
operators, so its orbit is shorter than the number of operators: the length of
the orbit IS the crystallographic multiplicity of the site.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

from rietcalc_demo.domain.cell import Vector
from rietcalc_demo.domain.structure import Structure

#: Two positions closer than this (in fractional units) are the same site.
SAME_SITE = 1e-4


@dataclass(frozen=True, slots=True)
class Image:
    """One atom of the unit cell: which independent atom it copies, and how."""

    atom: int  # index into Structure.atoms
    operator: int  # index into Structure.operators
    position: Vector  # folded into [0, 1)
    esd: Vector


def _fold(value: float) -> float:
    folded = value - math.floor(value)
    return 0.0 if folded > 1.0 - 1e-12 else folded


def _same_site(p: Vector, q: Vector) -> bool:
    for a, b in zip(p, q, strict=True):
        d = a - b
        if abs(d - round(d)) > SAME_SITE:
            return False
    return True


def orbit(structure: Structure, atom_index: int) -> tuple[Image, ...]:
    """The distinct images of one independent atom, in operator order."""
    atom = structure.atoms[atom_index]
    images: list[Image] = []
    for op_index, operator in enumerate(structure.operators):
        p = operator.apply(atom.position)
        position = (_fold(p[0]), _fold(p[1]), _fold(p[2]))
        if any(_same_site(position, image.position) for image in images):
            continue
        images.append(Image(atom_index, op_index, position, operator.apply_esd(atom.position_esd)))
    return tuple(images)


def expand(structure: Structure) -> tuple[Image, ...]:
    """Every atom in one unit cell."""
    return tuple(image for i in range(len(structure.atoms)) for image in orbit(structure, i))


def multiplicities(structure: Structure) -> tuple[int, ...]:
    """Number of atoms per cell generated by each independent atom."""
    return tuple(len(orbit(structure, i)) for i in range(len(structure.atoms)))
